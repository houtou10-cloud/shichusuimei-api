def calculate_twelve_stage(
    day_stem: str,
    branch: str,
) -> str:
    """
    日主の天干と各柱の地支から十二運を返します。

    例：
        乙 × 丑 -> 衰
        乙 × 未 -> 養
        乙 × 巳 -> 沐浴
        乙 × 亥 -> 死
    """
    if day_stem not in STEMS:
        raise ValueError(
            f"不正な日干です: {day_stem}"
        )

    if branch not in BRANCHES:
        raise ValueError(
            f"不正な地支です: {branch}"
        )

    return TWELVE_STAGES[day_stem][branch]
